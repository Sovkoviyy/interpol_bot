#!/usr/bin/env bash

# ====================================================================
#  INTERPOL BOT • Безопасное обновление без риска потери данных (Safe Update)
# ====================================================================
#  1. Создаёт резервную копию базы данных SQLite и файла .env
#  2. Сохраняет локальные изменения через git stash
#  3. Загружает свежий код из репозитория
#  4. Обновляет зависимости и выполняет сборку
#  5. Перезапускает процесс только после успешной сборки
# ====================================================================

set -e

echo "===================================================================="
echo "🛡️ [INTERPOL BOT] Безопасное обновление системы с авто-бэкапом данных"
echo "===================================================================="

ROOT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT_DIR"

TIMESTAMP=$(date +"%Y%m%d_%H%M%S")
BACKUP_DIR="$ROOT_DIR/backups/backup_$TIMESTAMP"

# --------------------------------------------------------------------
# 1. Автоматическое резервное копирование данных (База данных + .env)
# --------------------------------------------------------------------
echo -e "\n📦 [1/6] Создание резервной копии данных..."
mkdir -p "$BACKUP_DIR"

# Бэкап файла конфигурации .env
if [ -f "$ROOT_DIR/.env" ]; then
  cp "$ROOT_DIR/.env" "$BACKUP_DIR/.env"
  echo "   ✅ Конфигурация .env сохранена в: $BACKUP_DIR/.env"
fi

# Бэкап базы данных SQLite
DB_BACKED_UP=false
mkdir -p "$BACKUP_DIR/prisma/data"

for db_path in "$ROOT_DIR/dev.db"* "$ROOT_DIR/prisma/dev.db"* "$ROOT_DIR/prisma/data/"*.db* "$ROOT_DIR/data/"*.db*; do
  if [ -f "$db_path" ]; then
    # Сохраняем с сохранением относительного пути
    rel_path="${db_path#$ROOT_DIR/}"
    dest_dir="$BACKUP_DIR/$(dirname "$rel_path")"
    mkdir -p "$dest_dir"
    cp "$db_path" "$dest_dir/"
    DB_BACKED_UP=true
  fi
done

if [ "$DB_BACKED_UP" = true ]; then
  echo "   ✅ База данных успешно скопирована в: $BACKUP_DIR/"
else
  echo "   ℹ️ Файл локальной базы SQLite не найден (возможно, используется PostgreSQL)."
fi

# --------------------------------------------------------------------
# 2. Безопасная загрузка обновлений через Git (сохранение правок)
# --------------------------------------------------------------------
echo -e "\n📥 [2/6] Загрузка обновлений с GitHub..."

# Сохраняем локальные правки (если они были) в stash, чтобы ничего не стереть
if ! git diff-index --quiet HEAD -- 2>/dev/null; then
  echo "   ⚠️ Обнаружены локальные изменения. Сохраняю их в безопасный stash..."
  git stash save "Auto-stash before safe update $TIMESTAMP" || true
fi

# Определяем целевую ветку (по умолчанию текущая или v5)
CURRENT_BRANCH=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo "v5")
TARGET_BRANCH="${1:-$CURRENT_BRANCH}"
if [ "$TARGET_BRANCH" = "HEAD" ]; then TARGET_BRANCH="v5"; fi

echo "   Ветка для обновления: $TARGET_BRANCH"
git fetch origin "$TARGET_BRANCH"
git checkout "$TARGET_BRANCH" 2>/dev/null || true
git pull origin "$TARGET_BRANCH" --no-rebase || {
  echo "⚠️ Обычный pull вызвал конфликт. Загружаю актуальную версию origin/$TARGET_BRANCH..."
  git reset --hard "origin/$TARGET_BRANCH"
}

echo "   ✅ Исходный код успешно обновлен."

# --------------------------------------------------------------------
# 3. Обновление зависимостей (бэкенд и фронтенд)
# --------------------------------------------------------------------
echo -e "\n📦 [3/6] Проверка и установка зависимостей..."
npm install
npm --prefix web install

# --------------------------------------------------------------------
# 4. Безопасная синхронизация схемы базы данных Prisma
# --------------------------------------------------------------------
echo -e "\n🗄️ [4/6] Применение миграций Prisma (без сброса существующих таблиц)..."
npx prisma generate
# prisma db push только добавляет новые поля/таблицы и никогда не удаляет данные без флага --force-reset
npx prisma db push --accept-data-loss

# --------------------------------------------------------------------
# 5. Сборка проекта (выполняется до остановки текущего сервера)
# --------------------------------------------------------------------
echo -e "\n🔨 [5/6] Сборка веб-панели и TypeScript бэкенда..."
npm run build
echo "   ✅ Сборка успешно завершена!"

# --------------------------------------------------------------------
# 6. Бесшовный перезапуск приложения
# --------------------------------------------------------------------
echo -e "\n🚀 [6/6] Перезапуск приложения..."
if command -v pm2 >/dev/null 2>&1; then
  # Освобождаем порт от старых процессов, если они зависли
  if command -v fuser >/dev/null 2>&1; then
    fuser -k 3001/tcp 2>/dev/null || true
  fi
  pm2 restart ecosystem.config.js || pm2 start ecosystem.config.js
  pm2 save
  echo "   ✅ Приложение успешно перезапущено в PM2!"
else
  echo "   ℹ️ PM2 не обнаружен. Для запуска выполните: ./start.sh"
fi

# --------------------------------------------------------------------
# 7. Финальная проверка работоспособности
# --------------------------------------------------------------------
sleep 2
echo -e "\n🔍 Проверка доступности веб-сервера (порт 3001)..."
if command -v curl >/dev/null 2>&1; then
  HEALTH_CHECK=$(curl -s http://127.0.0.1:3001/api/health || true)
  if [[ "$HEALTH_CHECK" == *"ok"* ]]; then
    echo "   ✅ Сервер отвечает: $HEALTH_CHECK"
  else
    echo "   ⚠️ Предупреждение: Сервер еще инициализируется, проверьте статус командой: pm2 status"
  fi
fi

echo -e "\n===================================================================="
echo "🎉 БЕЗОПАСНОЕ ОБНОВЛЕНИЕ ЗАВЕРШЕНО УСПЕШНО!"
echo "📁 Точка восстановления сохранена в: $BACKUP_DIR"
echo "===================================================================="
