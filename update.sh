#!/usr/bin/env bash

# ====================================================================
#  INTERPOL BOT • Автоматическое полное обновление и пересборка на VPS
# ====================================================================

set -e

echo "===================================================================="
echo "🔄 [INTERPOL BOT] Полное обновление файлов и пересборка системы"
echo "===================================================================="

# 1. Переход в папку проекта
cd "$(dirname "$0")"

# 2. Остановка висящих процессов на порту 3001
echo -e "\n🛑 [1/6] Проверка и освобождение порта 3001..."
if command -v fuser >/dev/null 2>&1; then
  fuser -k 3001/tcp || true
fi

# 3. Синхронизация репозитория с GitHub
echo -e "\n📥 [2/6] Загрузка актуального кода с GitHub..."
git fetch --all
git reset --hard origin/main

# 4. Установка и обновление всех зависимостей
echo -e "\n📦 [3/6] Установка зависимостей (бэкенд и веб-интерфейс)..."
npm install
npm --prefix web install

# 5. Синхронизация базы данных Prisma
echo -e "\n🗄️ [4/6] Синхронизация базы данных Prisma..."
npx prisma generate
npx prisma db push --accept-data-loss

# 6. Полная пересборка TypeScript бэкенда и React фронтенда
echo -e "\n🔨 [5/6] Полная сборка фронтенда и бэкенда..."
npm run build

# 7. Перезапуск процесса
echo -e "\n🚀 [6/6] Запуск / перезапуск приложения..."
if command -v pm2 >/dev/null 2>&1; then
  pm2 restart ecosystem.config.js || pm2 start ecosystem.config.js
  pm2 save
  echo "✅ Приложение перезапущено в PM2!"
else
  echo "⚠️ PM2 не найден. Запустите бота вручную: ./start.sh"
fi

echo -e "\n✨ Проверка доступности сервера:"
sleep 2
if command -v curl >/dev/null 2>&1; then
  curl -s http://127.0.0.1:3001/api/health || true
  echo ""
fi

echo -e "\n🎉 Обновление успешно завершено! Веб-панель активна на порту 3001."
echo "===================================================================="
